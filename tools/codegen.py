import sys 
import os
import re #regular expressions

def get_namespaces(content, pos):
    # get all the namespaces in content
    ns_regex = re.compile(r'\bnamespace\s+([\w:]+)\s*\{')
    active_namespaces = []

    # walk through all the braces up to pos
    brace_depth = 0
    ns_depths = []

    # strip comments
    clean = re.sub(r'//.*?$|/\*.*?\*/', lambda m: ' ' * len(m.group(0)), content[:pos], flags=re.DOTALL | re.MULTILINE)

    tokens = re.finditer(r'\bnamespace\s+([\w:]+)\s*\{|\{|\}', clean)
    # loop through every token in namespace
    for match in tokens:
        if match.group(1):  # entered a namespace
            brace_depth += 1
            ns_depths.append((brace_depth, match.group(1)))
        elif match.group(0) == '{': # didn't enter, but we did hit an open bracket
            brace_depth += 1
        elif match.group(0) == '}': # closing bracket instead
            if ns_depths and ns_depths[-1][0] == brace_depth:
                ns_depths.pop()
            brace_depth = max(0, brace_depth - 1)
    
    return "::".join(ns for _, ns in ns_depths)

def gen_reflection(out_path, header_paths):

    # find classes, and everything up to the bracket after the class def {
    class_head_regex = re.compile(r'\b(?:class|struct)\s+(\w+)(?:\s*:\s*([^\{]+))?\{')
    # look for members with the PUBLIC keyword in front of them
    public_regex = re.compile(
        r'\bPUBLIC\s+'
        r'((?:[^;<>,=]|<(?:[^<>]|<(?:[^<>]|<[^<>]*>)*>)*>)+?)\s+'  # type (allows commas inside for some layers of nesting)
        r'([a-zA-Z_]\w*)\s*'                                       # field name
        r'(?:=\s*[^;]+|\{[^;]*\})?\s*;'                            # any default initializer
    )  

    generated_code = """/*          GENERATED BY CMAKE CODEGEN - DO NOT TOUCH         */
#include <reflectable.hpp>
#include <serialise.hpp>

// this is a lie 
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Winvalid-offsetof"

using namespace Engine;
"""

    includes = ""
    helper_functions = ""
    log_msg = f'reflectLogger().logInfo("Initialising reflection data...");'
    init_calls = f"\ninline void Engine::Reflection::initialiseReflectionData() {{ \n    {log_msg}\n"

    # loop through every header 
    for header in header_paths:
        if not os.path.exists(header):
            continue

        with open(header, 'r') as f:
            content = f.read()

        # look through all classes in this header (are there multiple?)
        for class_match in class_head_regex.finditer(content):
            class_name = class_match.group(1)
            
            # get inheritance stuff
            inheritance_chunk = class_match.group(2)
            
            # get all base names this class derives from 
            base_names = []
            if inheritance_chunk:
                for part in re.split(r',(?![^<]*>)', inheritance_chunk):
                    clean_base = re.sub(r'\b(?:public|protected|private|virtual)\b', '', part).strip()
                    if clean_base:
                        base_names.append(clean_base)

            # get the class contents
            start_idx = class_match.end()
            brace_count = 1
            class_body = ""
            for i in range(start_idx, len(content)):
                if content[i] == '{':
                    brace_count += 1
                elif content[i] == '}':
                    brace_count -= 1
                    if brace_count == 0:
                        class_body = content[start_idx:i]
                        break

            # check if this content has PUBLIC fields
            fields = public_regex.findall(class_body)
            
            is_resource = base_names and any(tag in base_names for tag in ("IResource"));
            if not fields:
                continue

            # get the enclosing namespaces
            ns = get_namespaces(content, class_match.start())

            full_class_name = f"{ns}::{class_name}" if ns else class_name
            full_class_names += full_class_name

            # create a safe function name (for example Engine_Physics_Rigidbody)
            safe_func_name = f"register_{full_class_name.replace('::', '_')}"

            # get headers we need to include
            header_inc = f'#include "{os.path.abspath(header)}"\n'
            if header_inc not in includes:
                includes += header_inc

            # we also need any parent fields (if this class inherits from something)
            clean_ns = ns.strip(": ") if ns else ""
            using_ns_line = f"using namespace {clean_ns};\n                " if clean_ns else ""

            parent_block = ""
            for b_name in base_names:
                parent_block += f"""
                        {{
                            {using_ns_line}using parent = {b_name};
                            if (Engine::Reflection::TypeInfo<parent>::descriptor.getFields != nullptr) {{
                                const size_t baseOffset = Engine::Reflection::getBaseOffset<{full_class_name}, parent>();
                                const auto& parentFields = Engine::Reflection::TypeInfo<parent>::descriptor.getFields();
                                for (auto f : parentFields) {{
                                    f.m_fieldOffset += baseOffset;
                                    localFields.insert(localFields.begin(), f);
                                }}
                            }}
                        }}"""

            # specialise TypeInfo<T>::init() inside the class's namespace so c++ knows what "base_name" is 
            spec_body = f"""template <>
inline void Engine::Reflection::TypeInfo<{full_class_name}>::initTypeInfo() {{
    descriptor = {{
        .name = "{class_name}",
        .fullName = "{full_class_name}",
        .getFields = []() -> const std::vector<Engine::ReflectableField>& {{
            static std::vector<Engine::ReflectableField> fields = []() {{
                std::vector<Engine::ReflectableField> localFields = {{
"""
            for f_type, f_name in fields:
                spec_body += f'                    {{ "{f_name}", offsetof({full_class_name}, {f_name}), "{f_type.strip()}" }},\n'
                clean_t = re.sub(r'\b(?:mutable|const)\b', '', f_type).strip()

                # for maps
                if (clean_t.startswith("std::unordered_map<") or clean_t.startswith("std::map<")) and clean_t.endswith(">"):
                    inner = clean_t[clean_t.find("<") + 1 : -1]
                    parts = [p.strip() for p in re.split(r',(?![^<]*>)', inner)]
                    if len(parts) == 2:
                        k_t, v_t = parts[0], parts[1]
                        init_calls += f'    Engine::Serialise::registerMapType<{clean_t}>("{clean_t}", "{k_t}", "{v_t}");\n'

                # for vectors
                if (clean_t.startswith("std::vector<") and clean_t.endswith(">")):
                    inner = clean_t[clean_t.find("<") + 1 : -1]
                    parts = [p.strip() for p in re.split(r',(?![^<]*>)', inner)]
                    if len(parts) == 1:
                        k_t = parts[0]
                        init_calls += f'    Engine::Serialise::registerVectorType<{k_t}>("{clean_t}", "{k_t}");\n'





            spec_body += f"""                }};{parent_block}
                return localFields;
            }}();
            return fields;
        }},
        .getFieldsForInstance = [](void* basePtr) -> std::vector<std::pair<Engine::ReflectableField, void*>> {{
            if constexpr (std::is_base_of_v<Engine::Reflection::IReflectable, {full_class_name}>) {{
                auto* typed = static_cast<{full_class_name}*>(static_cast<Engine::Reflection::IReflectable*>(basePtr));
                return Engine::Reflection::getObjectFields(typed);
            }} else {{
                auto* typed = static_cast<{full_class_name}*>(basePtr);
                return Engine::Reflection::getObjectFields(typed);
            }}
        }},
        .createInstance = []() -> std::shared_ptr<void> {{
            if constexpr (std::is_default_constructible_v<{full_class_name}>) {{
                std::shared_ptr<{full_class_name}> obj = std::shared_ptr<{full_class_name}>(new {full_class_name}());
                if constexpr (std::is_base_of_v<Engine::Reflection::IReflectable, {full_class_name}>) {{
                    obj->setTypeDescriptor(&Engine::Reflection::TypeInfo<{full_class_name}>::descriptor);
                }}
                return obj;
            }} else {{
                return nullptr;
            }}
        }}
    }};

    Engine::Reflection::getTypeRegistry()["{full_class_name}"] = &descriptor;
    Engine::Reflection::getTypeRegistry()["{class_name}"] = &descriptor;

    if constexpr (std::is_base_of_v<Engine::IResource, {full_class_name}>) {{
        Engine::Serialise::registerUniquePtrType<{full_class_name}>("std::unique_ptr<{class_name}>");
        Engine::Serialise::registerUniquePtrType<{full_class_name}>("std::unique_ptr<{full_class_name}>");
        Engine::Serialise::registerSharedPtrType<{full_class_name}>("std::shared_ptr<{class_name}>");
        Engine::Serialise::registerSharedPtrType<{full_class_name}>("std::shared_ptr<{full_class_name}>");
        Engine::Serialise::registerWeakPtrType<{full_class_name}>("std::weak_ptr<{class_name}>");
        Engine::Serialise::registerWeakPtrType<{full_class_name}>("std::weak_ptr<{full_class_name}>");
    }}
}}
"""
            helper_functions += f"\n{spec_body}\n"

            init_calls += f"    Engine::Reflection::TypeInfo<{full_class_name}>::initTypeInfo();\n"

    init_calls += "}\n"

    # actually write our generated code
    generated_code += includes + helper_functions + init_calls + "\nnamespace std {"

    # to ignore any warnings lol
    generated_code += "}\n#pragma GCC diagnostic pop\n"

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w') as f:
        f.write(generated_code)

if __name__ == "__main__":
    gen_reflection(sys.argv[1], sys.argv[2:])
